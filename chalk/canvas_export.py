"""Canvas-paste syllabus page HTML (F-03).

Renders course.json as the University of Utah Canvas syllabus template,
filled in, for the instructor to paste into the syllabus page's HTML
editor in place of the template (UAT round 2): the course banner, an
Instructor section, the Detailed Syllabus (learning objectives, grading,
and the schedule), and the template's standard Technical Issues and
Americans with Disabilities Act sections. Details course.json doesn't
hold (email, office hours, TAs) keep the template's own "Insert ..."
placeholders for the instructor to fill in on Canvas.

No external CSS and no JavaScript: Canvas strips both, so the template's
look (red banner, grey section bars) is inline styles.

The header comment's product name comes from chalk.branding at call time
— never a hardcoded literal (PLAN.md Risk #9).
"""

from __future__ import annotations

import datetime as dt
from html import escape
from pathlib import Path

from chalk import branding
from chalk.archiving import archive_before_write
from chalk.models import CourseData, CourseInfo, Week
from chalk.rollover.preview import break_name

_BANNER_STYLE = (
    "background-color: #be0000; color: #ffffff; text-align: center; padding: 12px 16px; "
    "border-radius: 6px; font-weight: normal;"
)
_SECTION_STYLE = "background-color: #c7cdd1; padding: 8px 16px; border-radius: 6px; font-weight: normal;"
_BODY_STYLE = "padding: 0 24px;"
_TABLE_STYLE = "border-collapse: collapse; width: 100%;"
_CELL_STYLE = "border: 1px solid #c7cdd1; padding: 6px 8px; text-align: left; vertical-align: top;"
_SCHEDULE_COLUMNS = ("Week", "Dates", "Topics", "Assignments")

# The template's standard sections, word for word.
_TECHNICAL_ISSUES = (
    "<p>You can get help with Canvas by using the Help menu on the left-side global navigation bar. "
    "From the help menu, you could "
    '<a href="https://community.canvaslms.com/t5/Student-Guide/tkb-p/student">search canvas guides</a>, '
    "report a problem, or contact 24/7 Canvas Support.</p>\n"
    "<p>You can also contact Utah TLT help desk by phone: 801-581-6112 during business hours or by email at "
    '<a href="mailto:classhelp@utah.edu">classhelp@utah.edu</a>.</p>'
)
_ACCESSIBILITY = (
    "<p>The University of Utah seeks to provide equal access to its programs, services, and activities for "
    "people with disabilities. If you will need accommodations in the class, reasonable prior notice needs "
    'to be given to the <a href="https://disability.utah.edu/">Center for Disability Services</a>, '
    "162 Union Building, 581-5020 (V/TDD). CDS will work with you and the instructor to make arrangements "
    "for accommodations.</p>"
)


def render_canvas_html(course_data: CourseData) -> str:
    """Return the Canvas syllabus page for `course_data`."""
    lines = [
        (
            f"<!-- Generated by {branding.PROJECT_NAME} — paste into the Canvas syllabus page's HTML editor, "
            "replacing the template -->"
        ),
        f'<h2 style="{_BANNER_STYLE}">{escape(_banner(course_data.course))}</h2>',
        _section("Instructor", _instructor(course_data.course)),
        _section("Detailed Syllabus", _detailed_syllabus(course_data)),
        _section("Technical Issues", _TECHNICAL_ISSUES),
        _section("Americans with Disabilities Act", _ACCESSIBILITY),
    ]
    return "\n".join(lines) + "\n"


def write_canvas_html(course_data: CourseData, output_path, *, eval_log_path=None) -> Path:
    """Write the Canvas HTML to `output_path` (normally
    outputs/canvas.html), archiving any previous version first."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    archive_before_write(output_path, eval_log_path=eval_log_path)
    output_path.write_text(render_canvas_html(course_data), encoding="utf-8")
    return output_path


def _banner(course: CourseInfo) -> str:
    """ "IS 6640 Networking and Servers": the course number and name, once
    each (a title often starts with the number already)."""
    if not course.number or course.number.replace(" ", "") in course.title.replace(" ", ""):
        return course.title
    return f"{course.number} - {course.title}"


def _section(title: str, body: str) -> str:
    return f'<h3 style="{_SECTION_STYLE}">{title}</h3>\n<div style="{_BODY_STYLE}">\n{body}\n</div>'


def _instructor(course: CourseInfo) -> str:
    rows = (
        ("", course.instructor or "Instructor goes here"),
        ("Email", "Insert email here"),
        ("Office Hours", "Insert office hours here"),
        ("Classroom", "TBA"),
        ("Time", course.meeting_pattern or "Insert class days and times here"),
        ("TA", "Insert TA here"),
        ("TA email", "Insert TA email here"),
    )
    return "\n".join(
        f"<p><strong>{escape(value)}</strong></p>" if not label else f"<p><strong>{label}:</strong> {escape(value)}</p>"
        for label, value in rows
    )


def _detailed_syllabus(course_data: CourseData) -> str:
    parts = []
    if course_data.learning_objectives:
        items = "".join(f"<li>{escape(item)}</li>" for item in course_data.learning_objectives)
        parts.append(f"<h4>Learning Objectives</h4>\n<ol>{items}</ol>")
    if course_data.assessments:
        rows = "\n".join(
            f'    <tr><td style="{_CELL_STYLE}">{escape(a.name)}</td>'
            f'<td style="{_CELL_STYLE}">{a.weight * 100:g}%</td></tr>'
            for a in course_data.assessments
        )
        parts.append(
            f'<h4>Grading</h4>\n<table style="{_TABLE_STYLE}">\n'
            f'  <thead><tr><th scope="col" style="{_CELL_STYLE}">Assessment</th>'
            f'<th scope="col" style="{_CELL_STYLE}">Weight</th></tr></thead>\n'
            f"  <tbody>\n{rows}\n  </tbody>\n</table>"
        )
    parts.append(f"<h4>{escape(course_data.course.term)} Schedule</h4>\n{_schedule_table(course_data)}")
    return "\n".join(parts)


def _schedule_table(course_data: CourseData) -> str:
    header_cells = "".join(
        f'<th scope="col" style="{_CELL_STYLE}">{column}</th>' for column in _SCHEDULE_COLUMNS
    )
    body_rows = [_render_week_row(week) for week in sorted(course_data.weeks, key=_week_sort_key)]
    lines = [
        f'<table style="{_TABLE_STYLE}">',
        f"  <thead><tr>{header_cells}</tr></thead>",
        "  <tbody>",
        *(f"    {row}" for row in body_rows),
        "  </tbody>",
        "</table>",
    ]
    return "\n".join(lines)


def _render_week_row(week: Week) -> str:
    if week.is_break:
        dates = f"{_short_date(week.date_start)} – {_short_date(week.date_end)}"
        return (
            f'<tr><th scope="row" style="{_CELL_STYLE}">—</th>'
            f'<td style="{_CELL_STYLE}">{dates}</td>'
            f'<td colspan="2" style="{_CELL_STYLE}"><strong>{escape(break_name(week.label))}</strong>'
            " — no class</td></tr>"
        )

    topics = _render_list(week.topics)
    if week.notes:
        topics += f"<p><em>{escape(week.notes)}</em></p>"
    return (
        f'<tr><th scope="row" style="{_CELL_STYLE}">Week {week.week_number}</th>'
        f'<td style="{_CELL_STYLE}">{_short_date(week.date)}</td>'
        f'<td style="{_CELL_STYLE}">{topics}</td>'
        f'<td style="{_CELL_STYLE}">{_render_list(week.assignments)}</td></tr>'
    )


def _render_list(items: list[str]) -> str:
    if not items:
        return ""
    return "<ul>" + "".join(f"<li>{escape(item)}</li>" for item in items) + "</ul>"


def _short_date(date: dt.date) -> str:
    return f"{date.strftime('%b')} {date.day}"


def _week_sort_key(week: Week) -> dt.date:
    return week.date if week.date is not None else week.date_start
