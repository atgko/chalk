def test_write_creates_the_file_and_archives_the_previous_version(tmp_path):
    output_path = tmp_path / "outputs" / "canvas.html"
    log_path = tmp_path / "eval-log.json"
    course_data = build_sample_course_data()

    write_canvas_html(course_data, output_path, eval_log_path=log_path)
    write_canvas_html(course_data, output_path, eval_log_path=log_path)

    assert output_path.read_text(encoding="utf-8") == render_canvas_html(course_data)
    assert len(list((output_path.parent / ".archive").iterdir())) == 1
    assert len(read_events_by_type(log_path, "archive")) == 1


def test_break_rows_do_not_repeat_the_dates_embedded_in_their_label():
    course_data = build_sample_course_data()
    weeks = [
        w.model_copy(update={"label": "Fall Break (10/10 - 10/18)"}) if w.is_break else w
        for w in course_data.weeks
    ]
    html = render_canvas_html(course_data.model_copy(update={"weeks": weeks}))
    assert "<strong>Fall Break</strong>" in html
    assert "10/10 - 10/18" not in html
